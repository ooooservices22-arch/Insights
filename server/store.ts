function ensureDb(): InsightsDatabase {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  if (!fs.existsSync(DB_FILE)) {
    fs.writeFileSync(DB_FILE, JSON.stringify(SEED_DATA, null, 2), 'utf-8');
    return structuredClone(SEED_DATA);
  }
  try {
    const raw = fs.readFileSync(DB_FILE, 'utf-8');
    const parsed = JSON.parse(raw) as Partial<InsightsDatabase>;
    const merged: InsightsDatabase = {
      ...structuredClone(SEED_DATA),
      ...parsed,
      contractors: parsed.contractors?.length ? parsed.contractors : structuredClone(SEED_DATA.contractors),
      groceryReports: parsed.groceryReports?.length ? parsed.groceryReports : structuredClone(SEED_DATA.groceryReports),
      powerOutages: parsed.powerOutages?.length ? parsed.powerOutages : structuredClone(SEED_DATA.powerOutages),
      usedEquipment: parsed.usedEquipment?.length ? parsed.usedEquipment : structuredClone(SEED_DATA.usedEquipment),
    };
    return merged;
  } catch {
    fs.writeFileSync(DB_FILE, JSON.stringify(SEED_DATA, null, 2), 'utf-8');
    return structuredClone(SEED_DATA);
  }
}

export function readDb(): InsightsDatabase {
  return ensureDb();
}

export function writeDb(next: InsightsDatabase): void {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
  const tmpFile = `${DB_FILE}.tmp`;
  fs.writeFileSync(tmpFile, JSON.stringify(next, null, 2), 'utf-8');
  fs.renameSync(tmpFile, DB_FILE);
}
